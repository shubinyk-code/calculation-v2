        c.zones.forEach(function (z) {
            d.add({ kind: 'break' });
            d.add({ kind: 'heading', text: 'Приложение № ' + z.appCalc + '. Гидравлический расчет ' + z.no + ' зоны ХПВ' });
            naporBlocks(c, z, calcBlocks[z.sys.id] || []).forEach(d.add);
        });
