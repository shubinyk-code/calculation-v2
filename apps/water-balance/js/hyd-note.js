        c.zones.forEach(function (z) { d.item('Приложение № ' + z.appCalc + ' – Гидравлический расчет ' + z.no + ' зоны ХПВ;'); });
        c.zones.forEach(function (z) { d.item('Приложение № ' + z.appCat + ' – Каталожные листы насосной станции хоз-питьевого водоснабжения ' + z.no + ' зоны;'); });

        d.add({ kind: 'break' });
        d.add({ kind: 'heading', text: 'Приложение № ' + c.appBalance + '. Баланс водопотребления' });
        d.add({ kind: 'title', text: 'Таблица 5. Годовой баланс систем водоснабжения.' });
