    /* Годовой баланс по корневым группам потребителей. */
    function annual(project, node, days) {
        var rows = [];
        var DAYS = days > 0 ? days : 365;
        var tot = { day: 0, loss: 0 };

        Consumers.roots(project).forEach(function (g) {
            var res = Consumers.runGroup(g.id, project, node);
            if (!res || !res.total) return;
            var loss = 0;
            Consumers.consumersInSubtree(g.id, project).forEach(function (cs) {
                var one = Consumers.run(cs, node);
                if (one && one.total) loss += one.total.qDay * Math.min(100, Math.max(0, cs.lossPercent || 0)) / 100;
            });
            rows.push([g.name, res.total.qDay * DAYS / 1000, res.total.qDay, res.total.qhr, loss * DAYS / 1000, loss]);
            tot.day += res.total.qDay; tot.loss += loss;
        });

        project.extras.forEach(function (e) {
            var day = Consumers.extraDay(e);
            if (!(day > 0)) return;
            rows.push([e.name, day * DAYS / 1000, day, '-', day * DAYS / 1000, day]);
            tot.day += day; tot.loss += day;
        });

        if (rows.length > 1) rows.push(['ИТОГО', tot.day * DAYS / 1000, tot.day, '-', tot.loss * DAYS / 1000, tot.loss]);

        return {
            kind: 'table',
            headRows: [
                [{ t: 'Наименование потребителя', rows: 2 }, { t: 'Расход хозяйственно-питьевой воды (В1+Т3)', span: 3 }, { t: 'Безвозвратные потери', span: 2 }],
                [{ t: 'тыс. м³/год' }, { t: 'м³/сут' }, { t: 'м³/час' }, { t: 'тыс. м³/год' }, { t: 'м³/сут' }]
            ],
            widths: [34, 14, 14, 14, 14, 14],
            digits: [null, 2, 3, 3, 4, 3],
            rows: rows,
            total: rows.length > 1 ? rows.length - 1 : undefined
        };
    }

