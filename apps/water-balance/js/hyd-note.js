    /* --- сборка ------------------------------------------------------------------ */

    /*
        В записке номер квартиры не нужен — только этаж диктующего прибора: «кв. 295» → «прибор на 17 этаже».
        Правится текст ячеек и строк в блоках расчёта напоров.
    */
    function noFlat(value, floor) {
        if (typeof value !== 'string') return value;
        return value.replace(/кв\. [^\s,;)]+/g, floor ? 'прибор на ' + floor + ' этаже' : 'прибор');
    }

    function noFlats(block, floor) {
        var out = Object.assign({}, block);
        if (typeof out.text === 'string') out.text = noFlat(out.text, floor);
        if (out.rows) out.rows = out.rows.map(function (row) { return Array.isArray(row) ? row.map(function (v) { return noFlat(v, floor); }) : row; });
        return out;
    }

    /* Блоки расчёта напоров по системам — из листа «Напоры» выгрузки в Excel. */
    function calcBlocks(result, hyd) {
        var blocks = HydReport.sheets(result, hyd)[0].blocks;
        var out = {};

        result.systems.forEach(function (sys) {
            var mine = [];
            blocks.forEach(function (b, i) {
                if (b.kind !== 'title' || b.text.indexOf(' — ' + sys.name) < 0) return;
                var t = blocks[i + 1];
                if (!t || t.kind !== 'table') return;
                var floor = sys.dict && sys.dict.leaf ? sys.dict.leaf.floor : 0;
                mine.push({ kind: 'title', text: b.text });
                mine.push(noFlats(Object.assign({}, t, t.head.length > 5 ? { size: 14, widths: [10, 30, 10, 15, 11, 10, 11, 10, 11, 12, 12, 12, 13, 13] } : { size: 18 }), floor));
            });
            out[sys.id] = mine;
        });

        return out;
    }

    /*
        Блоки записки. project — App.project; result — HydCalc.run. Возвращает
        { blocks, marks }, где marks — число пометок «[[…]]», требующих внимания.
    */
    function build(project, result, hyd) {
        if (!result || !result.input) throw new Error('на схеме нет ввода и стояков — записка строится по расчёту гидравлики');

        var c = context(project, result, hyd);
        var d = Doc();

        // номера приложений: 1 — паспорт счётчика, 2 — баланс, дальше расчёты зон и каталожные листы
        // (расходы воды и потери в счётчиках — таблицами 1, 2, 4 в тексте записки)
        c.appBalance = 2;
        var n = 3;
        c.zones.forEach(function (z) { z.appCalc = n++; });
        c.zones.forEach(function (z) { z.appCat = n++; });
        c.appPumps = c.zones.map(function (z) { return String(z.appCat); });

        var tables = { inputs: Report.inputsTable(), main: Report.template() };
        var pumpTable = HydPumps.blocks(result, hyd);
        var appNo = function (sys) { var z = c.zones.filter(function (x) { return x.sys === sys; })[0]; return z ? z.appCalc : ''; };

        sectionA(d, c);
        sectionV(d, c);
        sectionG(d, c, tables);
        sectionE(d, c, c.zones.length ? pumpTable : [], appNo);
        sectionZh(d, c);
        sectionZ(d, c);
        sectionL(d, c);
        sectionN(d, c);
        sectionT(d, c);
        appendices(d, c, calcBlocks(result, hyd));


        var list = [];
        d.blocks.forEach(function (b) {
            (String(b.text || '').match(/\[\[[^\]]*\]\]/g) || []).forEach(function (m) { list.push(m.slice(2, -2)); });
        });

        var work = calcBlocks(result, hyd);
        var napor = c.zones.map(function (z) { return { no: z.appCalc, zone: z, blocks: naporBlocks(c, z, work[z.sys.id] || []) }; });

        return { blocks: d.blocks, marks: list.length, list: list, name: c.name, context: c, napor: napor };
    }

    function fileName(c) {
        var base = (c && c.name ? c.name : 'Объект').replace(/[\\\/:*?"<>|]/g, '-');
        return base + ' — ИОС2 водоснабжение, записка.docx';
    }

    function title(name) { return 'ТЕКСТОВАЯ ЧАСТЬ' + (name ? ' — ' + name : ''); }

    function save(project, result, hyd) {
        var out = build(project, result, hyd);
        Docx.save([{ name: 'Записка', blocks: out.blocks }], title(out.name), fileName(out));
        return out;
    }

    /*
        Отдельная выгрузка приложения «Расчёт напоров» (по форме бюро) — Word. Номера приложений те же,
        что в записке. Это то, что идёт в стадию П; рабочие таблицы — saveWorkTables.
    */
    function saveNapor(project, result, hyd) {
        var out = build(project, result, hyd);
        var blocks = [];

        out.napor.forEach(function (a, i) {
            if (i) blocks.push({ kind: 'break' });
            blocks.push({ kind: 'heading', text: 'Приложение № ' + a.no + '. Гидравлический расчет ' + a.zone.no + ' зоны ХПВ' });
            a.blocks.forEach(function (b) { blocks.push(b); });
        });

        if (!blocks.length) throw new Error('насосных установок на схеме нет — приложение строится по зонам с насосами');
        var base = (out.name || 'Объект').replace(/[\\/:*?"<>|]/g, '-');
        Docx.save([{ name: 'Расчёт напоров', blocks: blocks }], 'РАСЧЁТ НАПОРОВ' + (out.name ? ' — ' + out.name : ''), base + ' — приложение, расчёт напоров.docx');
        return out;
    }

    /* Рабочий вид: напоры, участки и расчётные точки диктующего пути таблицами — не для записки и стадии П. */
    function saveWorkTables(project, result, hyd) {
        var work = calcBlocks(result, hyd);
        var blocks = [];

        result.systems.forEach(function (sys) {
            (work[sys.id] || []).forEach(function (b) { blocks.push(b); });
        });

        if (!blocks.length) throw new Error('расчётных таблиц нет');
        var name = hyd.survey.objectName || (project.object && project.object.name) || 'Объект';
        Docx.save([{ name: 'Напоры', blocks: blocks }], 'РАСЧЁТ НАПОРОВ, рабочие таблицы — ' + name, name.replace(/[\\/:*?"<>|]/g, '-') + ' — рабочие таблицы напоров.docx');
    }

    return { build: build, save: save, saveNapor: saveNapor, saveWorkTables: saveWorkTables, annual: annual, context: context, title: title, ask: ask };
