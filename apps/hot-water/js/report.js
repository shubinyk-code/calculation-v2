    function esc(value) {
        return String(value === null || value === undefined ? '' : value)
            .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
    }

    /** Число двумя цифрами — для даты. */
    function pad(value) {
        return (value < 10 ? '0' : '') + Fmt.int(value);
    }

    var tableNumber = 0;

    /*
        Одна таблица записки: номер, название, описание, сама таблица
        и расшифровка столбцов под ней. Расшифровка идёт после, а не до:
        сначала человек смотрит числа, и только если что-то непонятно —
        читает, что это за столбец.
    */
    function tableHtml(block) {
        tableNumber++;

        var html = '<h3>Таблица ' + tableNumber + ' — ' + esc(block.caption) + '</h3>';

        if (block.about)
            html += '<p class="about">' + esc(block.about) + '</p>';

        if (block.rows.length === 0) {
            html += '<p class="empty">Данных нет.</p>';
            return html;
        }

        html += '<table><thead><tr>';
        for (var c = 0; c < block.columns.length; c++)
            html += '<th>' + esc(block.columns[c]) + '</th>';
        html += '</tr></thead><tbody>';

        for (var r = 0; r < block.rows.length; r++) {
            var row = block.rows[r].cells || block.rows[r];
            html += '<tr>';
            for (var k = 0; k < row.length; k++)
                html += '<td>' + esc(row[k]) + '</td>';
            html += '</tr>';
        }

        html += '</tbody></table>';

        if (block.explain !== false)
            html += columnsHtml(block.columns, block.notes);

        return html;
    }

    /**
     * Расшифровка столбцов.
     *
     * Пропускается, если пояснять почти нечего: расшифровка из одной строки
     * под таблицей на четыре столбца выглядит как недоделка, а пользы не даёт.
     * Порог — половина столбцов: таблица, где понятна половина заголовков,
     * в пояснениях не нуждается.
     */
    function columnsHtml(columns, extra) {
        var known = [];

        for (var i = 0; i < columns.length; i++) {
            var note = (extra && extra[columns[i]]) || COLUMN_NOTES[columns[i]];
            if (note) known.push([columns[i], note]);
        }

        if (known.length * 2 < columns.length) return '';

        var html = '<p class="about">Что означают столбцы:</p>'
            + '<table class="notes"><tbody>';

        for (i = 0; i < known.length; i++) {
            html += '<tr><td class="name">' + esc(known[i][0]) + '</td>'
                + '<td>' + esc(known[i][1]) + '</td></tr>';
        }

        return html + '</tbody></table>';
    }

