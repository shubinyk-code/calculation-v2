'use strict';

/*
    Подбор дроссельных диафрагм (шайб).

    Диафрагма — пластина с отверстием: лишний напор срезается на сжатии струи.
    Через отверстие проходит тот же расход, что и по трубе, поэтому

        ΔH = Q² / (2g · (Cд · A)²),     A = π·d²/4,
        Cд = C / √(1 − β⁴),             β = d / D,

    где C — коэффициент расхода острокромочного отверстия (0,62), β — отношение
    диаметра отверстия к внутреннему диаметру трубы, D — внутренний диаметр
    трубы, в которой стоит шайба. Поправка 1/√(1 − β⁴) учитывает скорость
    подхода: у большого отверстия в узкой трубе поток уже разогнан.

    Обратная задача — по требуемому срезу ΔH найти d — решается несколькими
    приближениями: β зависит от d, поэтому начинаем без поправки и уточняем.

    Диаметр округляется ВВЕРХ до шага изготовления (обычно 1 мм). Вверх —
    намеренно: большее отверстие срезает меньше, и давление после шайбы
    остаётся не ниже требуемого. Округление вниз урезало бы расход ниже
    нормативного.

    Единицы: Q — л/с, ΔH — м вод. ст., d и D — мм.
*/

var Diaphragm = (function () {

    var G = 9.81;
    var C = 0.62;

    /** Потери на шайбе диаметром d в трубе D при расходе Q. */
    function head(q, d, D) {
        if (!(q > 0) || !(d > 0)) return 0;

        var dm = d / 1000;
        var area = Math.PI * dm * dm / 4;
        var beta = D > 0 ? Math.min(0.99, d / D) : 0;
        var cd = C / Math.sqrt(1 - Math.pow(beta, 4));
        var v = (q / 1000) / (cd * area);

        return v * v / (2 * G);
    }

    /**
        Диаметр отверстия, срезающего ΔH при расходе Q в трубе D.

        Потери убывают с ростом отверстия, поэтому корень ищется делением
        отрезка (0, D): простые последовательные приближения здесь зацикливались
        при малом срезе — отверстие получалось шире трубы, поправка β подскакивала
        и решение прыгало между двумя далёкими значениями.

        Ноль означает, что такой срез шайбой не получить: даже отверстие почти
        во всю трубу срезает больше.
    */
    function diameter(q, dH, D) {
        if (!(q > 0) || !(dH > 0)) return 0;

        if (!(D > 0)) {
            var area = (q / 1000) / (C * Math.sqrt(2 * G * dH));
            return 1000 * Math.sqrt(4 * area / Math.PI);
        }

        var hi = D * 0.999;
        if (head(q, hi, D) > dH) return 0;

        var lo = 0.01;
        for (var i = 0; i < 80; i++) {
            var mid = (lo + hi) / 2;
            if (head(q, mid, D) > dH) lo = mid;
            else hi = mid;
        }

        return (lo + hi) / 2;
    }

    /**
        Подбор шайбы: точный диаметр, изготовимый (вверх по шагу) и то, что
        получится на деле — сколько срежется и какое давление останется.
    */
    function pick(q, dH, D, options) {
        var o = options || {};
        var step = o.step > 0 ? o.step : 1;
        var min = o.min > 0 ? o.min : 6;
        var exact = diameter(q, dH, D);

        if (!(exact > 0)) {
            return { need: dH, exact: 0, d: 0, cut: 0, ok: false, reason: 'такой малый срез шайбой не получить' };
        }

        // Отверстие почти во всю трубу шайбой не считается: срезать почти нечего.
        if (D > 0 && exact > D * 0.85) {
            return { need: dH, exact: exact, d: 0, cut: 0, ok: false, reason: 'срез мал — шайба не нужна' };
        }

        /*
            Округление решает, в какую сторону ошибиться. Вверх — отверстие
            больше, срез меньше: давление останется выше нужного (годится, когда
            важно не занизить напор). Вниз — срез больше: давление гарантированно
            не превысит предел (годится для 0,45 МПа у ПК), но проверяйте, что
            напора ещё хватает.
        */
        var d = o.round === 'down'
            ? Math.floor((exact + 1e-9) / step) * step
            : Math.ceil((exact - 1e-9) / step) * step;
        if (d < min) d = min;

        var limit = D > 0 ? D - step : 0;
        if (limit > 0 && d > limit) {
            return { need: dH, exact: exact, d: 0, cut: 0, ok: false, reason: 'шайба не нужна: отверстие больше трубы' };
        }

        var cut = head(q, d, D);
        return {
            need: dH,
            exact: exact,
            d: d,
            cut: cut,
            beta: D > 0 ? d / D : 0,
            ok: true,
            reason: ''
        };
    }

    /**
        Диафрагма на стояк: срезает то, что лишнее у всех его этажей сразу —
        наименьший излишек. Остальное добирают поэтажные шайбы.
    */
    function common(needs) {
        var list = needs.filter(function (n) { return typeof n === 'number' && isFinite(n); });
        if (!list.length) return 0;
        return Math.max(0, Math.min.apply(null, list));
    }

    return {
        C: C,
        head: head,
        diameter: diameter,
        pick: pick,
        common: common
    };
})();
